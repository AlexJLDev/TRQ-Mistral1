/* i18n TRQ — dictionnaire FR -> EN + résolution locale de langue.
   Les clés sont les libellés français d'origine du code source ; t() renvoie
   l'anglais quand la langue active est 'en' (défaut), le texte source sinon. */

function trq_langs(): array {
    return ['fr' => 'Français', 'en' => 'English'];
}

/** Langue active : réglage utilisateur (settings.lang), défaut 'en'. Résolue une fois par requête. */
function trq_lang(): string {
    static $lang = null;
    if ($lang !== null) return $lang;
    $lang = 'en';
    try {
        $v = cfg('lang');
        if (is_string($v) && array_key_exists($v, trq_langs())) $lang = $v;
    } catch (\Throwable $e) {
    }
    return $lang;
}

