/** Traduit une chaîne : retourne la clé en français si la langue active est 'fr' ou traduction absente. */
function t(string $s): string {
    if (trq_lang() === 'fr') return $s;
    $d = trq_i18n();
    if (array_key_exists($s, $d)) return $d[$s];
    $alt = str_replace("'", "\u{2019}", $s);
    return array_key_exists($alt, $d) ? $d[$alt] : $s;
}

/** Cherche un libellé dans le dictionnaire (apostrophes normalisées). */
function trq_seek(array $d, string $s) {
    if (array_key_exists($s, $d)) return $d[$s];
    $alt = str_replace("'", "\u{2019}", $s);
    return array_key_exists($alt, $d) ? $d[$alt] : null;
}

/** Filtre de sortie : traduit les nœuds de texte HTML et les littéraux JS des scripts. */
function trq_translate_html(string $html): string {
    if (trq_lang() === 'fr') return $html;
    if ($html === '' || stripos($html, '<html') === false) return $html;
    $d = trq_i18n();
    $frags = [];
    foreach ($d as $k => $v) {
        if (mb_strlen($k) >= 8 && preg_match('/[\\s\\x{00a0}\\x{00ab}]/u', $k)) $frags[$k] = $v;
    }
    uksort($frags, fn($a, $b) => mb_strlen($b) <=> mb_strlen($a));

    $parts = preg_split('/(<script\b[^>]*>.*?<\/script>|<style\b[^>]*>.*?<\/style>)/is', $html, -1, PREG_SPLIT_DELIM_CAPTURE);
    if ($parts === false) return $html;
    foreach ($parts as $i => $part) {
        if ($part === '' || $part === null) continue;
        $isBlock = ($i % 2 === 1);
        if ($isBlock && preg_match('/^<script/i', $part)) {
            $q1 = chr(39);
            $q2 = chr(34);
            $jsRe = '/' . $q1 . '([^' . $q1 . '\\n]*)' . $q1 . '|' . $q2 . '([^' . $q2 . '\\n]*)' . $q2 . '/';
            $parts[$i] = preg_replace_callback(
                $jsRe,
                function ($m) use ($d, $q1, $q2) {
                    $raw = ($m[1] !== null) ? (string)$m[1] : (string)$m[2];
                    if ($raw === '') return $m[0];
                    $v = trq_seek($d, $raw);
                    if ($v === null || $v === $raw) return $m[0];
                    $esc = addcslashes($v, $q1 . $q2 . chr(92));
                    $q = ($m[1] !== null) ? $q1 : $q2;
                    return $q . $esc . $q;
                },
                $part
            );
            if ($parts[$i] === null) $parts[$i] = $part;
        } elseif (!$isBlock) {
            $seg = $part . '|';
            $res = preg_replace_callback('/>([^<>]+)</', function ($m) use ($d, $frags) {
                $txt = html_entity_decode($m[1], ENT_QUOTES | ENT_HTML5, 'UTF-8');
                $norm = str_replace("'", "\u{2019}", trim($txt));
                $out = null;
                if (array_key_exists($norm, $d)) {
                    $out = $d[$norm];
                } else {
                    foreach ($frags as $k => $v) $norm = strtr($norm, [$k => $v]);
                    $out = $norm;
                }
                $enc = htmlspecialchars($out, ENT_QUOTES | ENT_HTML5, 'UTF-8', false);
                return '>' . $enc . '<';
            }, $seg);
            if ($res === null) $res = $seg;
            $parts[$i] = substr($res, 0, -1);
        }
    }
    return implode('', $parts);
}
